import tkinter as tk
cua_so=tk.Tk()
cua_so.title("Cửa sổ Tkinter đầu tiên")
cua_so.geometry("400x300")
cua_so_2=tk.Tk()
cua_so_2.title("Ứng dụng demo")
cua_so_2.geometry("400x300")
cua_so_2.resizable(False, False)
nhan=tk.Label(cua_so_2,text="Xin chào Tkinter",font=("Arial",16))
nhan.pack(pady=20)

cua_so_3=tk.Tk()
cua_so_3.title("Ví dụ Frame")
cua_so_3.geometry("400x300")
khung_tren=tk.Frame(cua_so_3,bg="light blue",height=100)
khung_tren.pack(fill="x")
khung_duoi=tk.Frame(cua_so_3,bg="lightyellow")
khung_duoi.pack(fill="both",expand=True)
tk.Label(khung_tren,text="Khu vực tiêu đề",bg="light blue").pack(pady=10)
tk.Label(khung_duoi,text="Khu vực nội dung",bg="lightyellow").pack(pady=10)
cua_so_3.mainloop()

